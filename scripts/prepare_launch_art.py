#!/usr/bin/env python3
"""Encode the supplied Launch artwork for MUI Bodychunk (requires ImageMagick)."""
from pathlib import Path
import subprocess
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'development/borders-20261016/assets/launch.png'
OUTPUT=ROOT/'development/borders-20261016/source/launch-art.h'
def main():
 width,height,depth=192,64,6
 raw=subprocess.check_output(['magick',str(SOURCE),'-resize',f'{width}x{height}!','+dither','-colors','63','-depth','8','rgba:-'])
 assert len(raw)==width*height*4
 palette=[(0,0,0)];lookup={};pixels=[]
 for at in range(0,len(raw),4):
  r,g,b,a=raw[at:at+4];rgb=(r,g,b)
  if a<128:pixels.append(0);continue
  if rgb not in lookup:lookup[rgb]=len(palette);palette.append(rgb)
  pixels.append(lookup[rgb])
 assert len(palette)<=1<<depth
 palette += [(0,0,0)]*((1<<depth)-len(palette))
 stride=((width+15)//16)*2;body=bytearray(height*stride*depth)
 for y in range(height):
  for x in range(width):
   value=pixels[y*width+x]
   for bit in range(depth):
    if value&(1<<bit):body[(y*depth+bit)*stride+x//8]|=1<<(7-x%8)
 text='/* Generated by scripts/prepare_launch_art.py from supplied assets/launch.png. */\n'
 text+=f'#define LAUNCH_WIDTH {width}\n#define LAUNCH_HEIGHT {height}\n#define LAUNCH_DEPTH {depth}\n'
 text+='static const UBYTE launch_body[]={'+','.join(map(str,body))+'};\n'
 text+='static const ULONG launch_colours[]={'+','.join(hex(c*0x01010101)for rgb in palette for c in rgb)+'};\n'
 OUTPUT.write_text(text)
 print('Encoded Launch artwork:',len(body),'planar bytes')
if __name__=='__main__':main()
